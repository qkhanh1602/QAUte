package com.example.TuVanSinhVien;
import com.example.TuVanSinhVien.entity.*;
import com.example.TuVanSinhVien.repository.*;
import com.example.TuVanSinhVien.service.*;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.bean.override.mockito.MockitoBean;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.jdbc.core.JdbcTemplate;
import java.time.*;
import java.util.*;
import java.util.concurrent.*;
import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest(properties="app.workflow.scheduling.enabled=false")
class ConcurrentWorkflowTests {
    @Autowired TicketService tickets;
    @Autowired AppointmentService appointments;
    @Autowired YeuCauTuVanRepository ticketRepo;
    @Autowired SinhVienRepository studentRepo;
    @Autowired NguoiTuVanRepository advisorRepo;
    @Autowired LinhVucTuVanRepository fieldRepo;
    @Autowired LichHenTuVanRepository appointmentRepo;
    @Autowired KhungGioTuVanRepository slotRepo;
    @Autowired PlatformTransactionManager transactions;
    @Autowired JdbcTemplate jdbc;
    // No user-facing notifications are generated by these tests.
    @MockitoBean NotificationService notifications;
    private <T> T tx(java.util.function.Supplier<T> action) { return new TransactionTemplate(transactions).execute(s -> action.get()); }
    private NguoiTuVan advisor() {
        return tx(() -> advisorRepo.findAllWithAccountAndUnit().stream().filter(a -> Boolean.TRUE.equals(a.getNhanTuVan()) && "HoatDong".equals(a.getTaiKhoan().getTrangThai())).findFirst().orElseThrow());
    }
    private List<SinhVien> students() {
        return tx(() -> studentRepo.findAll().stream().filter(s -> "HoatDong".equals(s.getTaiKhoan().getTrangThai()) && appointmentRepo.countPendingByStudent(s.getMaSV())<2).peek(s -> org.hibernate.Hibernate.initialize(s.getTaiKhoan())).limit(2).toList());
    }
    private int race(Runnable a, Runnable b) throws Exception {
        try(var pool=Executors.newFixedThreadPool(2)) {
            var ready=new CountDownLatch(2);var start=new CountDownLatch(1);
            java.util.function.Function<Runnable,Callable<Boolean>> task=action -> () -> { ready.countDown(); start.await(); try { action.run(); return true; } catch(IllegalStateException ex) { return false; } };
            Future<Boolean> x=pool.submit(task.apply(a)),y=pool.submit(task.apply(b));
            assertTrue(ready.await(5,TimeUnit.SECONDS));start.countDown();
            return (x.get(20,TimeUnit.SECONDS)?1:0)+(y.get(20,TimeUnit.SECONDS)?1:0);
        }
    }
    @Test void onlyOneConcurrentClaimCommits() throws Exception {
        NguoiTuVan advisor=advisor();SinhVien student=students().getFirst();
        Integer id=tx(() -> {
            LinhVucTuVan field=fieldRepo.findAll().stream().filter(f -> f.getDonVi().getMaDonVi().equals(advisor.getDonVi().getMaDonVi())).findFirst().orElseThrow();
            LocalDateTime now=LocalDateTime.now();
            return ticketRepo.saveAndFlush(YeuCauTuVan.builder().sinhVien(student).donVi(advisor.getDonVi()).linhVuc(field)
                .tieuDe("TEST_RACE_"+UUID.randomUUID()).noiDung("Dữ liệu tạm để kiểm thử đồng thời, tự xóa sau test.")
                .trangThai("ChoTiepNhan").ngayTao(now).ngayCapNhat(now).hanTiepNhan(now.plusDays(7)).hanSLA(now.plusDays(7)).build()).getMaYeuCau();
        });
        try {
            assertEquals(1,race(() -> tickets.claimTicket(id,advisor),() -> tickets.claimTicket(id,advisor)));
            assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM PhanCongTuVan WHERE MaYeuCau=?",Integer.class,id));
        } finally {
            tx(() -> { jdbc.update("DELETE FROM LichSuYeuCau WHERE MaYeuCau=?",id);jdbc.update("DELETE FROM PhanCongTuVan WHERE MaYeuCau=?",id);jdbc.update("DELETE FROM YeuCauTuVan WHERE MaYeuCau=?",id);return null; });
        }
    }
    @Test void onlyOneStudentCanReserveSlot() throws Exception {
        NguoiTuVan advisor=advisor();List<SinhVien> students=students();assertEquals(2,students.size());
        LocalDate day=LocalDate.now(ZoneId.of("Asia/Ho_Chi_Minh")).plusDays(2);
        while(day.getDayOfWeek().getValue()>5) day=day.plusDays(1);
        LocalDateTime start=day.atTime(9,0);
        Integer id=appointments.createSlot(advisor,start,start.plusMinutes(45),"TrucTuyen","https://example.com/test-race").getMaKhungGio();
        try {
            assertEquals(1,race(() -> appointments.bookAppointment(students.get(0),id,"TEST_RACE","Kiểm thử đồng thời."),() -> appointments.bookAppointment(students.get(1),id,"TEST_RACE","Kiểm thử đồng thời.")));
            assertEquals(1,jdbc.queryForObject("SELECT COUNT(*) FROM LichHenTuVan WHERE MaKhungGio=?",Integer.class,id));
        } finally {
            tx(() -> { jdbc.update("DELETE FROM LichHenTuVan WHERE MaKhungGio=?",id);jdbc.update("DELETE FROM KhungGioTuVan WHERE MaKhungGio=?",id);return null; });
        }
    }
}
